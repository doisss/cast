class _StubLayout(S.Layout):
    """Layout with every path redirected into a temp directory.

    local_bin matters most: without it a test would write a symlink into the
    real ~/.local/bin and clobber the user's installation.
    """

    def __init__(self, root):
        super().__init__(system=False)
        self.bin = str(root / "bin")
        self.etc = str(root / "etc")
        self.data = str(root / "data")

    @property
    def falco_etc(self):
        return os.path.join(self.etc, "falco")

    @property
    def local_bin(self):
        return os.path.join(self.data, "localbin")

    @property
    def local_share(self):
        return os.path.join(self.data, "share")


def _tarball_with(path, member, payload):
    with tarfile.open(path, "w:gz") as tar:
        info = tarfile.TarInfo(member)
        info.size = len(payload)
        tar.addfile(info, io.BytesIO(payload))
    return str(path)


def _stub_download(monkeypatch, src):
    monkeypatch.setattr(S, "_download",
                        lambda url, dest, timeout=0: shutil.copy(src, dest))


def test_install_trivy_extracts_verifies_and_publishes(tmp_path, monkeypatch):
    lay = _StubLayout(tmp_path)
    payload = b'#!/bin/sh\necho "Version: 0.99.0"\n'
    archive = _tarball_with(tmp_path / "t.tar.gz", "trivy", payload)
    monkeypatch.setattr(S, "trivy_asset",
                        lambda: ("https://example.invalid/t", "0.99.0"))
    _stub_download(monkeypatch, archive)
    msg = S.install_trivy(lay)
    assert msg.startswith("ok")
    assert (tmp_path / "bin" / "trivy").read_bytes() == payload
    assert os.access(tmp_path / "bin" / "trivy", os.X_OK)
    # and the symlink landed in the temp dir, not in the real ~/.local/bin
    assert pathlib.Path(lay.local_bin).joinpath("trivy").is_symlink()


