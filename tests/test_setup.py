def test_setup_does_not_run_at_import():
    """I-10: importing sarbar.setup must not touch the network."""
    import importlib
    import sys
    for mod in list(sys.modules):
        if mod.startswith("sarbar"):
            del sys.modules[mod]
    calls = []
    real = S.urllib.request.urlretrieve
    module = importlib.import_module("sarbar.setup")
    module.urllib.request.urlretrieve = lambda url, dest: calls.append(url)
    assert calls == [], "import must not download anything"
    module.urllib.request.urlretrieve = real


