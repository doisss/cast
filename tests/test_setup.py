def _fake_falco_tree(root, payload):
    os.makedirs(os.path.join(root, "usr", "bin"), exist_ok=True)
    os.makedirs(os.path.join(root, "etc", "falco"), exist_ok=True)
    os.makedirs(os.path.join(root, "usr", "share", "falco", "plugins"), exist_ok=True)
    with open(os.path.join(root, "usr", "bin", "falco"), "wb") as fh:
        fh.write(payload)
    with open(os.path.join(root, "usr", "bin", "falcoctl"), "wb") as fh:
        fh.write(b'#!/bin/sh\necho "falcoctl 2"\n')
    for name in ("falco.yaml", "falco_rules.yaml"):
        with open(os.path.join(root, "etc", "falco", name), "w") as fh:
            fh.write("x\n")
    with open(os.path.join(root, "usr", "share", "falco", "plugins",
                           "libcontainer.so"), "wb") as fh:
        fh.write(b"\x7fELF plugin")
    return os.path.join(root, "usr", "bin", "falco")


